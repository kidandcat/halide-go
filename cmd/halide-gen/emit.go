package main

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
	"unicode"
)

func emitGo(pkg, base string, filters []filter) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, `// Code generated by halide-gen. DO NOT EDIT.

package %s

import (
	"embed"
	"sync"

	"github.com/kidandcat/halide-go"
)

//go:embed libs
var embedded embed.FS

// Pipeline is the set of Halide filters in this package.
type Pipeline struct {
	lib *halide.Library
`, pkg)
	for _, f := range filters {
		fmt.Fprintf(&b, "\t%s *halide.Func\n", unexport(exportName(f.CName)))
	}
	b.WriteString("}\n\n")

	b.WriteString(`// Load opens the embedded library for this process.
// Native is the default. Pass halide.WithBackend(halide.WASM), or build with
// -tags halidewasm, to run the wasm-simd module instead.
func Load(opts ...halide.Option) (*Pipeline, error) {
	lib, err := halide.OpenEmbedded(embedded, "` + base + `", opts...)
	if err != nil {
		return nil, err
	}
	p := &Pipeline{lib: lib}
	var ferr error
`)
	for _, f := range filters {
		field := unexport(exportName(f.CName))
		fmt.Fprintf(&b, "\tif p.%s, ferr = lib.Func(%q); ferr != nil {\n\t\tlib.Close()\n\t\treturn nil, ferr\n\t}\n", field, f.CName)
	}
	b.WriteString("\treturn p, nil\n}\n\n")
	b.WriteString(`// Close releases the library and shuts down its Halide thread pool.
func (p *Pipeline) Close() error {
	if p == nil || p.lib == nil {
		return nil
	}
	return p.lib.Close()
}

`)

	for _, f := range filters {
		if err := emitMethod(&b, f); err != nil {
			return nil, err
		}
	}

	b.WriteString(`var (
	defaultOnce sync.Once
	defaultPipe *Pipeline
	defaultErr  error
)

// Default loads the package pipeline once.
func Default() (*Pipeline, error) {
	defaultOnce.Do(func() {
		defaultPipe, defaultErr = Load()
	})
	return defaultPipe, defaultErr
}

`)
	for _, f := range filters {
		if err := emitFunc(&b, f); err != nil {
			return nil, err
		}
	}
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated Go: %w\n%s", err, b.String())
	}
	return out, nil
}

func emitMethod(b *bytes.Buffer, f filter) error {
	params, call, err := signature(f)
	if err != nil {
		return err
	}
	field := unexport(exportName(f.CName))
	fmt.Fprintf(b, "// %s runs the Halide filter %s.\nfunc (p *Pipeline) %s(%s) error {\n\treturn p.%s.Call(%s)\n}\n\n",
		exportName(f.CName), f.CName, exportName(f.CName), params, field, call)
	return nil
}

func emitFunc(b *bytes.Buffer, f filter) error {
	params, call, err := signature(f)
	if err != nil {
		return err
	}
	fmt.Fprintf(b, "// %s loads the default pipeline and runs %s.\nfunc %s(%s) error {\n\tp, err := Default()\n\tif err != nil {\n\t\treturn err\n\t}\n\treturn p.%s(%s)\n}\n\n",
		exportName(f.CName), f.CName, exportName(f.CName), params, exportName(f.CName), call)
	return nil
}

func signature(f filter) (params, call string, err error) {
	var ps, cs []string
	used := map[string]bool{}
	for _, a := range f.Args {
		gt, err := a.goType()
		if err != nil {
			return "", "", fmt.Errorf("%s: %w", f.CName, err)
		}
		name := goParam(a.Name, used)
		ps = append(ps, name+" "+gt)
		cs = append(cs, name)
	}
	return strings.Join(ps, ", "), strings.Join(cs, ", "), nil
}

func goParam(name string, used map[string]bool) string {
	n := sanitize(name)
	if n == "" {
		n = "arg"
	}
	base := n
	for i := 2; used[n]; i++ {
		n = fmt.Sprintf("%s%d", base, i)
	}
	used[n] = true
	return n
}

func sanitize(name string) string {
	var b strings.Builder
	for _, r := range name {
		if unicode.IsLetter(r) || unicode.IsDigit(r) || r == '_' {
			b.WriteRune(r)
		} else {
			b.WriteByte('_')
		}
	}
	s := b.String()
	if s == "" {
		return "arg"
	}
	if s[0] >= '0' && s[0] <= '9' {
		s = "v" + s
	}
	if goKeywords[s] {
		s += "_"
	}
	return s
}

func exportName(c string) string {
	parts := strings.FieldsFunc(c, func(r rune) bool { return r == '_' || r == '-' })
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]))
		if len(p) > 1 {
			b.WriteString(p[1:])
		}
	}
	if b.Len() == 0 {
		return "Filter"
	}
	return b.String()
}

func unexport(name string) string {
	if name == "" {
		return "fn"
	}
	r := []rune(name)
	r[0] = unicode.ToLower(r[0])
	s := string(r)
	if goKeywords[s] {
		s += "Fn"
	}
	return s
}

var goKeywords = map[string]bool{
	"break": true, "default": true, "func": true, "interface": true, "select": true,
	"case": true, "defer": true, "go": true, "map": true, "struct": true,
	"chan": true, "else": true, "goto": true, "package": true, "switch": true,
	"const": true, "fallthrough": true, "if": true, "range": true, "type": true,
	"continue": true, "for": true, "import": true, "return": true, "var": true,
}
